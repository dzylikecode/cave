import 'dart:io';

import 'package:ffigen/ffigen.dart';

Future<void> main() async {
  final root = Platform.script.resolve('../');
  await FfiGenerator(
    input: Input(
      entryPoints: [root.resolve('third_party/bgfx/include/bgfx/c99/bgfx.h')],
      include: (uri) => uri.path.contains('/bgfx/'),
      compilerOptions: [
        '-I',
        root.resolve('third_party/bgfx/include').toFilePath(),
      ],
    ),
    output: Output(
      dart: DartOutput(path: root.resolve('lib/src/third_party/bgfx.g.dart')),
      recordUseMapping: root.resolve(
        'lib/src/third_party/bgfx.record_use_mapping.g.dart',
      ),
      style: NativeExternalBindings(
        assetId: 'package:bgfx/src/third_party/bgfx.g.dart',
      ),
      preamble:
          '// Copyright 2011-2026 Branimir Karadzic. All rights reserved.\n'
          '// bgfx is licensed under BSD-2-Clause; see third_party/bgfx/LICENSE.\n'
          '// Generated by package:ffigen. Do not edit manually.\n'
          '// ignore_for_file: unused_field',
    ),
    visitors: [
      Visitor(
        func: (node) {
          node.isIncluded =
              node.originalName.startsWith('bgfx_') &&
              !{
                'bgfx_dbg_text_printf',
                'bgfx_dbg_text_vprintf',
                'bgfx_get_interface',
              }.contains(node.originalName);
          node.recordUse = node.isIncluded;
        },
        struct: (node) {
          node.isIncluded = node.originalName.startsWith('bgfx_');
        },
        enumClass: (node) {
          node.isIncluded = node.originalName.startsWith('bgfx_');
          if (node.originalName == 'bgfx_render_frame') {
            node.name = 'BgfxRenderFrame';
          }
        },
        typealias: (node) {
          node.isIncluded = node.originalName.startsWith('bgfx_')
              ? .always
              : .never;
        },
        macroConstant: (node) {
          node.isIncluded = node.originalName.startsWith('BGFX_');
        },
      ),
    ],
  ).generate();
}
