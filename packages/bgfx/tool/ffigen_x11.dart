import 'dart:io';

import 'package:ffigen/ffigen.dart';

Future<void> main() async {
  final root = Platform.script.resolve('../');
  await FfiGenerator(
    input: Input(
      entryPoints: [root.resolve('third_party/x11/window.h')],
      include: (uri) => uri.path.contains('/X11/'),
    ),
    output: Output(
      dart: DartOutput(
        path: root.resolve('example/lib/src/third_party/x11.g.dart'),
      ),
      style: DynamicLibraryBindings(wrapperName: 'X11'),
      preamble:
          '// Copyright 1985, 1986, 1987, 1991, 1998 The Open Group.\n'
          '// See third_party/x11/LICENSE. Generated by package:ffigen. Do not edit.\n'
          '// ignore_for_file: unused_field',
    ),
    visitors: [
      Visitor(
        func: (node) {
          node.isIncluded = {
            'XOpenDisplay',
            'XDefaultRootWindow',
            'XCreateSimpleWindow',
            'XStoreName',
            'XSelectInput',
            'XInternAtom',
            'XSetWMProtocols',
            'XMapWindow',
            'XFlush',
            'XPending',
            'XNextEvent',
            'XLookupKeysym',
            'XGetWindowAttributes',
            'XDestroyWindow',
            'XCloseDisplay',
          }.contains(node.originalName);
        },
        struct: (node) {
          node.isIncluded = {
            'XWindowAttributes',
            'XKeyEvent',
          }.contains(node.originalName);
        },
        union: (node) {
          node.isIncluded = node.originalName == '_XEvent';
          if (node.originalName == '_XEvent') node.name = 'XEvent';
        },
        typealias: (node) {
          node.isIncluded = .never;
        },
        macroConstant: (node) {
          node.isIncluded = {
            'KeyPress',
            'KeyPressMask',
            'StructureNotifyMask',
            'ClientMessage',
            'DestroyNotify',
            'ConfigureNotify',
          }.contains(node.originalName);
        },
      ),
    ],
  ).generate();
}
